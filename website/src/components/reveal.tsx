'use client';

import { useEffect, useRef } from 'react';

/**
 * Content rises into place as it comes into view. The hidden state is plain CSS
 * (`.reveal` in globals.css), so with JavaScript off the `<noscript>` override
 * on the page shows everything immediately — a scroll animation is never
 * allowed to be the reason a page is blank. Reduced motion skips it entirely.
 *
 * It is always a `<div>`: inside a list, wrap it in the `<li>` rather than
 * asking this to become one, so the list stays a list.
 */
export function Reveal({
  children,
  delay = 0,
  className = '',
}: {
  children: React.ReactNode;
  delay?: number;
  className?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const node = ref.current;
    if (!node) return;

    if (
      typeof IntersectionObserver === 'undefined' ||
      window.matchMedia('(prefers-reduced-motion: reduce)').matches
    ) {
      node.classList.add('is-visible');
      return;
    }

    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            entry.target.classList.add('is-visible');
            observer.unobserve(entry.target);
          }
        }
      },
      { rootMargin: '0px 0px -12% 0px', threshold: 0.08 },
    );

    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`reveal ${className}`.trim()}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
    >
      {children}
    </div>
  );
}
