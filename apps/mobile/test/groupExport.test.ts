/** Build a minimal but complete expense row. */
function expense(
  id: string,
  overrides: {
    description?: string;
    category?: string | null;
    amount: string;
    currency?: string;
    date?: string;
    payer: string;
    shares: string[];
    deleted?: boolean;
  },
): ExpenseRow {
  const currency = overrides.currency ?? 'INR';
  const each = (BigInt(overrides.amount) / BigInt(overrides.shares.length)).toString();
  return {
    id,
    group_id: 'g-1',
    deleted_at: overrides.deleted ? '2026-08-20T00:00:00.000Z' : null,
    created_at: '2026-08-01T00:00:00.000Z',
    currentVersion: {
      id: `${id}-v1`,
      version_no: 1,
      description: overrides.description ?? '',
      category: overrides.category ?? null,
      category_meta: null,
      expense_date: overrides.date ?? '2026-08-08',
      currency,
      amount: overrides.amount,
      split_type: 'equal',
      split_params: { kind: 'equal' } as never,
      author_member_id: overrides.payer,
      notes: null,
      payment_method: null,
      receipt_share_url: null,
      location: null,
      created_at: '2026-08-01T00:00:00.000Z',
      payers: [{ member_id: overrides.payer, amount: overrides.amount }],
      shares: overrides.shares.map((member) => ({ member_id: member, amount: each })),
    },
  };
}

