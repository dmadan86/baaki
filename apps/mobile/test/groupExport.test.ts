describe('buildGroupExportModel', () => {
  it('assembles group meta, counts and per-currency totals', () => {
    const model = buildGroupExportModel(makeInput());

    expect(model.groupName).toBe('Goa Trip');
    expect(model.coverEmoji).toBe('🏖️');
    expect(model.groupType).toBe('Trip');
    expect(model.currency).toBe('INR');
    expect(model.memberCount).toBe(3);
    // Deleted expenses stay in the list (append-only ledger)…
    expect(model.expenseCount).toBe(2);
    expect(model.settlementCount).toBe(1);

    // …but are excluded from the spend totals.
    expect(model.totals).toHaveLength(1);
    expect(model.totals[0].amount.currency).toBe('INR');
    expect(model.totals[0].amount.minor).toBe(120000n);
    expect(model.totals[0].amount.value).toBe(1200);
    expect(model.totals[0].count).toBe(1);
  });

  it('resolves names, categories, split participants and formats money', () => {
    const model = buildGroupExportModel(makeInput());
    const dinner = model.expenses.find((row) => row.id === 'e-1')!;

    expect(dinner.description).toBe('Dinner');
    expect(dinner.category).toBe('Food & drink');
    expect(dinner.paidBy).toBe('Asha');
    expect(dinner.participants).toBe('Asha, Bala');
    expect(dinner.participantCount).toBe(2);
    expect(dinner.deleted).toBe(false);
    // INR minor units → localized display + summable major value.
    expect(dinner.amount.value).toBe(1200);
    expect(dinner.amount.text).toContain('₹');
    expect(dinner.amount.text).toContain('1,200');

    const cab = model.expenses.find((row) => row.id === 'e-2')!;
    expect(cab.deleted).toBe(true);
  });

  it('derives balances with direction and a clean magnitude', () => {
    const model = buildGroupExportModel(makeInput());
    const asha = model.balances.find((row) => row.memberId === 'm-asha')!;
    const bala = model.balances.find((row) => row.memberId === 'm-bala')!;
    const ghost = model.balances.find((row) => row.memberId === 'm-ghost')!;

    expect(asha.direction).toBe(BalanceDir.Owed);
    expect(asha.directionText).toBe('is owed');
    expect(asha.signedValue).toBe(600);
    // The magnitude carries no minus — the direction word does that job.
    expect(asha.amount.text).not.toContain('-');
    expect(asha.amount.text).toContain('600');

    expect(bala.direction).toBe(BalanceDir.Owes);
    expect(bala.signedValue).toBe(-600);
    expect(bala.amount.text).not.toContain('-');

    expect(ghost.direction).toBe(BalanceDir.Settled);
    expect(ghost.directionText).toBe('settled up');
    expect(ghost.signedValue).toBe(0);
  });

  it('maps roles and localizes the settlement method', () => {
    const model = buildGroupExportModel(makeInput());
    expect(model.members[0].role).toBe('Admin');
    expect(model.members[1].role).toBe('Member');
    expect(model.members[2].isGhost).toBe(true);

    expect(model.settlements[0].from).toBe('Bala');
    expect(model.settlements[0].to).toBe('Asha');
    expect(model.settlements[0].method).toBe('Cash');
    expect(model.settlements[0].amount.value).toBe(600);
  });

  it('flags Arabic as RTL', () => {
    expect(isRtlLocale('ar')).toBe(true);
    expect(isRtlLocale('ar-EG')).toBe(true);
    expect(isRtlLocale('en-IN')).toBe(false);
    expect(buildGroupExportModel(makeInput('ar')).isRtl).toBe(true);
    expect(buildGroupExportModel(makeInput('en-IN')).isRtl).toBe(false);
  });
});

// --- HTML template ---------------------------------------------------------

describe('renderGroupExportHtml', () => {
  it('includes the header, summary and all three tables with money', () => {
    const html = renderGroupExportHtml(buildGroupExportModel(makeInput()), PDF_LABELS);

    expect(html).toContain('Goa Trip');
    expect(html).toContain('Waves');
    expect(html).toContain('Trip');
    // Summary band labels + counts.
    expect(html).toContain('Total spent');
    expect(html).toContain('Balances');
    // Table headers.
    expect(html).toContain('Paid by');
    expect(html).toContain('From');
    expect(html).toContain('Method');
    // Rows.
    expect(html).toContain('Dinner');
    expect(html).toContain('Asha');
    expect(html).toContain('is owed');
    // Money renders with symbol.
    expect(html).toContain('₹');
    // Deleted expense is kept and tagged, not dropped.
    expect(html).toContain('Cancelled cab');
    expect(html).toContain('deleted');
    // Footer.
    expect(html).toContain('Generated by Waves');
  });

  it('is LTR for English and RTL for Arabic', () => {
    const ltr = renderGroupExportHtml(buildGroupExportModel(makeInput('en-IN')), PDF_LABELS);
    expect(ltr).toContain('dir="ltr"');

    const rtl = renderGroupExportHtml(buildGroupExportModel(makeInput('ar')), PDF_LABELS);
    expect(rtl).toContain('dir="rtl"');
  });

  it('escapes HTML in dynamic text', () => {
    const input = makeInput();
    const withMarkup = {
      ...input,
      expenses: [
        expense('e-x', {
          description: '<script>alert(1)</script>',
          amount: '10000',
          payer: 'm-asha',
          shares: ['m-asha'],
        }),
      ],
    };
    const html = renderGroupExportHtml(buildGroupExportModel(withMarkup), PDF_LABELS);
    expect(html).toContain('&lt;script&gt;');
    expect(html).not.toContain('<script>alert(1)</script>');
  });

  it('escapeHtml handles the dangerous characters', () => {
    expect(escapeHtml('a & b < c > d "e" \'f\'')).toBe(
      'a &amp; b &lt; c &gt; d &quot;e&quot; &#39;f&#39;',
    );
  });
});

// --- Excel workbook --------------------------------------------------------

describe('buildGroupExportWorkbook', () => {
  it('builds the five expected sheets', () => {
    const wb = buildGroupExportWorkbook(buildGroupExportModel(makeInput()), SHEET_LABELS);
    expect(wb.SheetNames).toEqual(['Summary', 'Expenses', 'Settlements', 'Balances', 'Members']);
  });

  it('writes expense money as a numeric major value beside its currency', () => {
    const wb = buildGroupExportWorkbook(buildGroupExportModel(makeInput()), SHEET_LABELS);
    const rows = XLSX.utils.sheet_to_json<Record<string, unknown>>(wb.Sheets.Expenses);
    const dinner = rows.find((row) => row.Description === 'Dinner')!;

    expect(dinner['Paid by']).toBe('Asha');
    expect(dinner.Amount).toBe(1200);
    expect(typeof dinner.Amount).toBe('number');
    expect(dinner.Currency).toBe('INR');
    expect(dinner.Deleted).toBe('No');
  });

  it('writes signed balances that sum to zero', () => {
    const wb = buildGroupExportWorkbook(buildGroupExportModel(makeInput()), SHEET_LABELS);
    const rows = XLSX.utils.sheet_to_json<Record<string, unknown>>(wb.Sheets.Balances);
    const sum = rows.reduce((total, row) => total + (row.Balance as number), 0);
    expect(sum).toBe(0);
  });

  it('serialises to a base64 .xlsx (zip) payload', () => {
    const wb = buildGroupExportWorkbook(buildGroupExportModel(makeInput()), SHEET_LABELS);
    const base64 = workbookToBase64(wb);
    expect(typeof base64).toBe('string');
    expect(base64.length).toBeGreaterThan(0);
    // A .xlsx is a zip; its first bytes are "PK" → base64 begins "UEs".
    expect(base64.startsWith('UEs')).toBe(true);
  });
});
