// --- write to the generated module -------------------------------------------

function writeFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function writeWearModule(projectRoot) {
  const wear = path.join(projectRoot, 'android', 'wear');
  const pkgDir = path.join(wear, 'src', 'main', 'java', ...WEAR_PACKAGE.split('.'));

  writeFile(path.join(wear, 'build.gradle'), buildGradle);
  writeFile(path.join(wear, 'src', 'main', 'AndroidManifest.xml'), manifest);
  writeFile(path.join(pkgDir, 'WearRelay.kt'), relayKt);
  writeFile(path.join(pkgDir, 'PhoneListenerService.kt'), listenerKt);
  writeFile(path.join(pkgDir, 'MainActivity.kt'), mainActivityKt);
}

module.exports = function withWavesWear(config) {
  config = includeWearModule(config);
  config = addComposeClasspath(config);
  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      writeWearModule(cfg.modRequest.projectRoot);
      return cfg;
    },
  ]);
  return config;
};

