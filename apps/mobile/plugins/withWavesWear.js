/**
 * The Wear OS companion — a standalone `:wear` Gradle module.
 *
 * A thin Wear Compose app that sends quick-add / voice / request-recent intents
 * to the paired phone over the Wearable Data Layer and renders what the phone
 * relays back. All ledger logic stays on the phone (src/lib/watch/bridge.tsx);
 * the shared transport is the WavesWatch Expo module. The watchOS sibling lives
 * in targets/watch.
 *
 * `android/` is generated and gitignored, so the whole module is emitted here at
 * prebuild — its build.gradle, manifest, Compose sources and resources — and
 * `settings.gradle` is taught to `include ':wear'` (the same withSettingsGradle
 * hook withShortNativeBuildPath.js uses). The module is standalone (not embedded
 * via `wearApp`), so it builds and installs independently of the phone APK.
 *
 * UNVERIFIED: authored on Windows with no Android/Wear build. The Wear Compose /
 * Kotlin / AGP version matrix in particular must be reconciled against the
 * generated android/ on a real emulator build before trust.
 */

